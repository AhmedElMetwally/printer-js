class Printer
{
    /**
     * @param {string} text
     * @param {string} [shape="#"] drawn for filled cells
     * @param {string} [space=" "] drawn for empty cells (keep it the same length as shape)
     */
    constructor(text, shape = "#", space = " ")
    {
        if (typeof text !== "string") {
            throw new TypeError("Printer: text must be a string");
        }
        this.text = text;
        this._shape = shape;
        this._space = space;
        this.word = [];
    }

    write()
    {
        const glyphs = Array.from(this.text.toUpperCase().replace(/\s/g, " "), (char) => {
            const glyph = FONT[char];
            if (!glyph) {
                throw new Error(`Printer: unsupported character ${JSON.stringify(char)}`);
            }
            return glyph;
        });

        this.word = [];
        for (let row = 0; row < HEIGHT; row++) {
            this.word.push(glyphs.map((glyph) => this._render(glyph, row)).join(this._space.repeat(GAP)));
        }
        return this;
    }

    print()
    {
        for (const line of this.word) {
            if (typeof window === "undefined") {
                console.log("\x1b[36m%s\x1b[0m", line);
            } else {
                console.log("%c%s", "color: #1797B1; font-weight: bold", line);
            }
        }
        return this;
    }

    toString()
    {
        return this.word.join("\n");
    }

    _render(glyph, row)
    {
        const width = Math.max(...glyph.map((line) => line.length));
        return Array.from(glyph[row].padEnd(width), (cell) => (cell === "#" ? this._shape : this._space)).join("");
    }
}

Printer.chars = Object.keys(FONT).join("");

if (typeof module !== "undefined" && module.exports) {
    module.exports = Printer;
} else if (typeof window !== "undefined") {
    window.Printer = Printer;
}
